CHARMAP_ES = {ch: cid for ch, cid, _, _, _, _ in SPANISH_GLYPHS_SPEC}


def _build_patched_bank(raw_bank: bytearray, rom_reader, lut_delta: int = 0) -> bytes:
    """
    1. Desplaza los 487 glifos 1-byte +1px Y (baseline r09 -> r10) si aún no están desplazados.
    2. Inyecta los 28 bitmaps Romance en 0xC4..0xDD y 0xAD..0xAE validando la LUT.
    """
    a_off = 0x0098 * 12
    already_shifted = (raw_bank[a_off] == 0x00 and raw_bank[a_off + 1] == 0x10)

    if not already_shifted:
        for g_idx in range(TOTAL_GLYPHS):
            off = g_idx * 12
            glyph = raw_bank[off : off + 12]
            if glyph[11] == 0x00:
                raw_bank[off : off + 12] = bytes([0x00]) + glyph[:11]

    for ch, cid, lut_off, g_idx, bmp_off, bmp_bytes in SPANISH_GLYPHS_SPEC:
        target_lut_off = lut_off + lut_delta
        lut_bytes = rom_reader(target_lut_off, 2)
        actual_idx = struct.unpack("<H", lut_bytes)[0]
        if actual_idx != g_idx:
            raise ValueError(
                f"LUT desalineada en 0x{target_lut_off:06X} para '{ch}': "
                f"esperado 0x{g_idx:04X}, hallado 0x{actual_idx:04X}"
            )
        rel_bmp = bmp_off - FONT_1BYTE_BASE
        raw_bank[rel_bmp : rel_bmp + 12] = bmp_bytes

    return bytes(raw_bank)


def apply_font_patch(project) -> dict:
    """Punto de entrada para FoMT Studio (llamado desde parche_n.py)."""
    bank_size = FONT_1BYTE_END - FONT_1BYTE_BASE
    is_mfomt = getattr(project, "is_mfomt", False)
    font_base = FONT_1BYTE_BASE_MFOMT if is_mfomt else FONT_1BYTE_BASE
    lut_delta = (LUT_1BYTE_BASE_MFOMT - LUT_1BYTE_BASE) if is_mfomt else 0

    raw_bank = bytearray(project.read_rom(font_base, bank_size))
    patched_bank = _build_patched_bank(raw_bank, project.read_rom, lut_delta=lut_delta)
    project.write_patch(font_base, patched_bank)
    return dict(CHARMAP_ES)


def patch_rom_standalone(in_rom: str, out_rom: str) -> None:
    """Permite parchar una ROM .gba directamente desde terminal sin abrir FoMT Studio."""
    with open(in_rom, "rb") as f:
        rom = bytearray(f.read())

    bank_size = FONT_1BYTE_END - FONT_1BYTE_BASE
    raw_bank = bytearray(rom[FONT_1BYTE_BASE : FONT_1BYTE_BASE + bank_size])
    patched_bank = _build_patched_bank(raw_bank, lambda off, sz: bytes(rom[off : off + sz]))
    rom[FONT_1BYTE_BASE : FONT_1BYTE_BASE + bank_size] = patched_bank

    with open(out_rom, "wb") as f:
        f.write(rom)
    print(f"ROM parcheada correctamente (0xC4..0xDD + 0xAD..0xAE - 28 caracteres Romance): {out_rom}")


