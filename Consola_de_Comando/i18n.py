def tr(key, lang="es"):
    lang_dict = TRANSLATIONS.get(lang, TRANSLATIONS["es"])
    return lang_dict.get(key, key)

def get_lang_from_widget(widget, fallback="es"):
    p = widget
    while p:
        if hasattr(p, 'current_lang'):
            return p.current_lang
        if hasattr(p, 'window') and hasattr(p.window, 'current_lang'):
            return p.window.current_lang
        try:
            p = p.parent()
        except:
            break
    return fallback
